-- Create the tables shown in the diagram

/*
PATTERNS

Each pattern is assigned a unique, numbered identifier generated by a sequence
Its name is the exact name of the garment to be made
The sizes comply with European standards and range from 32 to 54
The commercial name may differ from the name
*/
create sequence pattern_seq
start with 1
nomaxvalue
nocycle
increment by 1;

create table patterns(
    pattern_id number primary key,
    pattern_name varchar2(255),
    sizing number(2,0),
    commercial_name varchar2(30),

    constraint size_larger check (sizing >= 32),
    constraint size_smaller check (sizing <= 54)
);

/*
FABRICS

The primary key of the table storing tailoring fabrics is text
The fabric’s natural origin is stored as a boolean (natural or artifical material)
*/

create table fabrics(
    id_tag char(10) primary key,
    name varchar2(25 char), --we use "char" because we want it to be 25 characters long, it would mean 25 bytes otherwise
    color varchar2(15 char),
    naturality number(1, 0)
);


/*
FINISHED PRODUCTS

In the finished products table, the primary key is assigned by a sequence
The tailor ID is the ID of the student who made the garment
The default value for the creation date is today's date
*/
create sequence fin_prod_seq
start with 1
increment by 1
nomaxvalue
nocycle;

create table finished_products(
    product_id number default fin_prod_seq.nextval primary key, 
    pattern_id number references patterns(pattern_id),
    fabric_id char(10) references fabrics(id_tag),
    user_id varchar2(50),
    creation_time date default sysdate
);

