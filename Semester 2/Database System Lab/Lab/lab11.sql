/*
Permissions

This allows us to follow the principle that everyone has access only to what they absolutely need

Permissions can be granted for every object

Granting/Giving permissions: GRANT (Your wish is granted)
Revoking/Taking permissions: REVOKE 

Permissions can be granted to: - a user
                       - a user group (user_group)
                       - everyone (public)
Any permission that can be granted can also be revoked
Permissions can be transferred: with grant option -> if specified this way, the user can grant their own permissions to others (while retaining them for themselves) 

What permissions can be granted:
- Select
- Insert
- Update
- Delete
- References
- Alter
- Index
- All (All of the above)
*/

-- Grant read permissions to user U_UXF1FP
grant select on fabrics to public; 

